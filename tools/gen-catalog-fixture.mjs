// Emits tests/lua/fixtures/<char>_catalog.lua - the real command_display entries,
// trimmed to the fields the Catalog actually reads.
//
// The Catalog tests run against real game data rather than invented entries,
// because the failure this code exists to prevent is data-shaped: a move that
// quietly drops out of the catalog, or one that is credited with a one-button
// input it does not have. Neither shows up against a fixture someone wrote by
// hand to match their own assumptions.
//
// Trimmed, not whole: the source file is ~270KB of which the vast majority is
// per-route audit metadata (confidence strings, evidence flags, charge-context
// fields). Carrying that into a Lua fixture would make it unreadable without
// making it more truthful.
//
//   node tools/gen-catalog-fixture.mjs [Character]

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname } from 'node:path'

const character = process.argv[2] ?? 'Zangief'
const src = `reframework/data/TrainingComboTrials_data/command_display/${character}.json`
const out = `tests/lua/fixtures/${character.toLowerCase()}_catalog.lua`

const catalog = JSON.parse(readFileSync(src, 'utf8'))
const meta = catalog._meta ?? {}

// UTF-8 as decimal escapes: the display strings carry Chinese strength tokens,
// and an escaped form survives any editor or git autocrlf setting.
const lua = (s) =>
  '"' + [...Buffer.from(String(s), 'utf8')]
    .map((b) => (b >= 0x20 && b < 0x7f && b !== 0x22 && b !== 0x5c
      ? String.fromCharCode(b)
      : '\\' + b))
    .join('') + '"'

const val = (v) => {
  if (v === null || v === undefined) return 'nil'
  if (typeof v === 'boolean') return v ? 'true' : 'false'
  if (typeof v === 'number') return String(v)
  return lua(v)
}

const ROUTE_FIELDS = [
  'profile', 'raw_button_mask', 'visible_direction', 'visible_button',
  'required_button_count', 'assist_combo_evidence', 'trigger_index',
]

const ids = Object.keys(catalog).filter((k) => /^\d+$/.test(k)).sort((a, b) => +a - +b)

const body = []
body.push(`-- GENERATED by tools/gen-catalog-fixture.mjs -- do not edit by hand.`)
body.push(`--`)
body.push(`-- Real entries from ${src}, trimmed to the fields core/Catalog.lua reads.`)
body.push(`-- schema        ${meta.schema ?? '?'}`)
body.push(`-- character     ${meta.character ?? character} (fighter_id ${meta.fighter_id ?? '?'})`)
body.push(`-- generated_at  ${meta.generated_at ?? '?'}`)
body.push(`-- entries       ${ids.length}`)
body.push(``)
body.push(`return {`)
body.push(`    _meta = {`)
body.push(`        schema = ${val(meta.schema)},`)
body.push(`        character = ${val(meta.character ?? character)},`)
body.push(`        fighter_id = ${val(meta.fighter_id)},`)
body.push(`        generated_at = ${val(meta.generated_at)},`)
body.push(`        ac_sha256 = ${val(meta.ac_sha256)},`)
body.push(`        bcm_sha256 = ${val(meta.bcm_sha256)},`)
body.push(`    },`)

for (const id of ids) {
  const e = catalog[id]
  body.push(`    [${lua(id)}] = {`)
  body.push(`        control_support = ${val(e.control_support)},`)
  body.push(`        ownership = ${val(e.ownership)},`)
  for (const [field, key] of [['classic_command', 'classic'], ['simple_command', 'simple'], ['motion_command', 'motion']]) {
    const d = e[field]?.display
    body.push(`        ${field} = ${d ? `{ display = ${lua(d)} }` : 'nil'},`)
  }
  const routes = Array.isArray(e.routes) ? e.routes : []
  if (routes.length === 0) {
    body.push(`        routes = {},`)
  } else {
    body.push(`        routes = {`)
    for (const r of routes) {
      const parts = ROUTE_FIELDS
        .filter((f) => r[f] !== undefined && r[f] !== null)
        .map((f) => `${f} = ${val(r[f])}`)
      body.push(`            { ${parts.join(', ')} },`)
    }
    body.push(`        },`)
  }
  body.push(`    },`)
}
body.push(`}`)

mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, body.join('\n') + '\n', 'utf8')
console.log(`${out}: ${ids.length} entries from ${character}`)
