// Regenerates tests/lua/fixtures/<char>_notations.lua from the shipped
// command_display catalog.
//
// The InputMask parser has to survive every notation the real catalog contains,
// not a sample someone typed by hand -- a notation it cannot parse is a move
// that silently vanishes from the Move Catalog. So the fixture is generated
// from the data and committed, and this script is how it is refreshed after a
// catalog update.
//
//   node tools/gen-notation-fixture.mjs [Character]

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname } from 'node:path'

const character = process.argv[2] ?? 'Zangief'
const src = `reframework/data/TrainingComboTrials_data/command_display/${character}.json`
const out = `tests/lua/fixtures/${character.toLowerCase()}_notations.lua`

const catalog = JSON.parse(readFileSync(src, 'utf8'))

// Only the Modern forms. classic_command is not something the Explorer ever
// compiles: the whole project is Modern-first, and classic notation uses a
// different button vocabulary.
const notations = new Set()
for (const [key, entry] of Object.entries(catalog)) {
  if (key === '_meta' || typeof entry !== 'object' || entry === null) continue
  for (const field of ['simple_command', 'motion_command']) {
    const display = entry[field]?.display
    if (typeof display === 'string' && display.trim() !== '') notations.add(display)
  }
}

const sorted = [...notations].sort()

// Lua long-bracket strings would choke on a notation containing ']]', and these
// are UTF-8 byte sequences, so emit them as decimal escapes: unambiguous, and
// it survives any editor or git autocrlf setting.
const escape = (s) =>
  '"' + [...Buffer.from(s, 'utf8')]
    .map((b) => (b >= 0x20 && b < 0x7f && b !== 0x22 && b !== 0x5c
      ? String.fromCharCode(b)
      : '\\' + b))
    .join('') + '"'

const meta = catalog._meta ?? {}
const body = `-- GENERATED by tools/gen-notation-fixture.mjs -- do not edit by hand.
--
-- Every distinct Modern notation (simple_command / motion_command display) in
-- ${src}
-- schema        ${meta.schema ?? '?'}
-- character     ${meta.character ?? character} (fighter_id ${meta.fighter_id ?? '?'})
-- generated_at  ${meta.generated_at ?? '?'}
--
-- Non-ASCII bytes are escaped decimally so the file is encoding-proof.

return {
${sorted.map((s) => `    ${escape(s)},`).join('\n')}
}
`

mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, body, 'utf8')
console.log(`${out}: ${sorted.length} distinct notations from ${character}`)
